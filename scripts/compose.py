#!/usr/bin/env python3
"""Composes the Containerfile of a devkit: a base image plus features, in the order of the kit file.

    python3 scripts/compose.py <kit> [--commit SHA]        # prints the Containerfile for kits/<kit>.json

Shape (like a devcontainer.json with features, without the tool and without registries):

* `base.json`            the base image, always by digest;
* `features/<id>/`       `feature.json` (id, description, options) and `install.sh` (runs once as root during the build);
* `kits/<name>.json`     description, `apt_snapshot` (a date of snapshot.debian.org: the same kit gives the same packages), `features` (a list; order matters).

The build context of the Containerfile is the root of this repository (the `COPY features/<id>` lines). After the features the image is hardened the way
every image of the factory is: no setuid bits, user `worker` (uid 1000), no `claude`, no token. Each feature directory gets a digest as a LABEL, so an image
tells what it was built from. The script only writes text; building is done by the factory (`infra/factory-test/build-devkit.sh`). Standard library only.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAME = re.compile(r"[a-z0-9]([a-z0-9-]{0,40}[a-z0-9])?")
SNAPSHOT = re.compile(r"\d{8}T\d{6}Z")
DIGEST = re.compile(r".+@sha256:[0-9a-f]{64}")
OPTION = re.compile(r"[a-z][a-z0-9_]{0,30}")


class KitError(ValueError):
    """The kit or one of its features is not usable; the message says why."""


def load(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise KitError(f"{path.name}: not readable as JSON ({exc})") from exc
    if not isinstance(data, dict):
        raise KitError(f"{path.name}: must be a JSON object")
    return data


def digest_of(directory: Path) -> str:
    """One sha256 over the names and the contents of the files of a feature (stable order)."""
    h = hashlib.sha256()
    for path in sorted(p for p in directory.rglob("*") if p.is_file()):
        h.update(str(path.relative_to(directory)).encode() + b"\0" + path.read_bytes() + b"\0")
    return h.hexdigest()


def feature(root: Path, feature_id: str) -> dict:
    if not NAME.fullmatch(feature_id):
        raise KitError(f"feature name {feature_id!r}: a-z, 0-9 and - only")
    directory = root / "features" / feature_id
    if not (directory / "install.sh").is_file():
        raise KitError(f"feature {feature_id}: no install.sh")
    meta = load(directory / "feature.json")
    if meta.get("id") != feature_id:
        raise KitError(f"feature {feature_id}: feature.json names another id ({meta.get('id')!r})")
    options = meta.get("options", {})
    if not isinstance(options, dict) or not all(OPTION.fullmatch(name) for name in options):
        raise KitError(f"feature {feature_id}: options must be an object with lower case names")
    return meta


def compose(kit: str, root: Path = ROOT, commit: str = "") -> str:
    if not NAME.fullmatch(kit):
        raise KitError(f"kit name {kit!r}: a-z, 0-9 and - only")
    base = load(root / "base.json")
    image = str(base.get("image", ""))
    if not DIGEST.fullmatch(image):
        raise KitError("base.json: the image must be given by digest (name@sha256:...)")
    spec = load(root / "kits" / f"{kit}.json")
    snapshot = str(spec.get("apt_snapshot", ""))
    if not SNAPSHOT.fullmatch(snapshot):
        raise KitError(f"kit {kit}: apt_snapshot must look like 20261019T000000Z")
    ids = spec.get("features")
    if not isinstance(ids, list) or not ids or len(ids) != len(set(ids)) or not all(isinstance(i, str) for i in ids):
        raise KitError(f"kit {kit}: features must be a non-empty list without duplicates")
    metas = [feature(root, feature_id) for feature_id in ids]

    lines = [
        f"# Devkit {kit}: {spec.get('description', '')}".rstrip(),
        "# Generated by scripts/compose.py; do not edit. Build context: the root of the devkits repository.",
        f"FROM {image}",
        "ENV DEBIAN_FRONTEND=noninteractive",
        "RUN rm -f /etc/apt/sources.list /etc/apt/sources.list.d/* \\",
        "    && printf 'Types: deb\\nURIs: http://snapshot.debian.org/archive/debian/%s/\\nSuites: trixie\\nComponents: main\\nSigned-By: /usr/share/keyrings/debian-archive-keyring.pgp\\nCheck-Valid-Until: no\\n' "
        f"'{snapshot}' > /etc/apt/sources.list.d/snapshot.sources",
    ]
    labels = {"org.opencontainers.image.title": f"devkit-{kit}", "devkit.kit": kit, "devkit.apt_snapshot": snapshot}
    for feature_id, meta in zip(ids, metas, strict=True):
        digest = digest_of(root / "features" / feature_id)
        labels[f"devkit.feature.{feature_id}"] = digest[:16]
        lines += [
            f"COPY features/{feature_id}/ /tmp/devkit/{feature_id}/",
            f"RUN cd /tmp/devkit/{feature_id} && bash ./install.sh \\",
            f"    && rm -rf /tmp/devkit/{feature_id} /var/lib/apt/lists/*",
        ]
    if commit:
        labels["devkit.commit"] = commit
    lines += [
        "RUN find / -xdev -type f -perm /6000 -exec chmod a-s {} + \\",
        "    && test -z \"$(find / -xdev -type f -perm /6000)\"",
        "RUN useradd --uid 1000 --user-group --create-home --home-dir /home/worker --shell /usr/sbin/nologin worker",
        "ENV HOME=/home/worker PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1",
        "LABEL " + " \\\n      ".join(f'{key}="{value}"' for key, value in labels.items()),
        "USER 1000:1000",
        "WORKDIR /",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Containerfile of a devkit")
    parser.add_argument("kit")
    parser.add_argument("--commit", default="", help="commit of this repository, recorded as a label")
    args = parser.parse_args(argv)
    try:
        sys.stdout.write(compose(args.kit, ROOT, args.commit))
    except KitError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
